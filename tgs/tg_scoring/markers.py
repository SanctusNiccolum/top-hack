def _compile(patterns: dict[str, list[str]]) -> dict[str, re.Pattern[str]]:
    return {
        category: re.compile("|".join(f"(?:{p})" for p in pats), re.IGNORECASE)
        for category, pats in patterns.items()
    }


_COMPILED = _compile(MARKERS)
_COMPILED_DOMAINS = _compile(DOMAIN_MARKERS)

TOTAL_PATTERNS = sum(len(v) for v in MARKERS.values()) + sum(
    len(v) for v in DOMAIN_MARKERS.values()
)


def normalize_for_matching(text: str) -> str:
    return text.lower().replace("ё", "е")


def find_marker_categories(text: str) -> set[str]:
    """Какие категории потенциально задеты. Пустое множество — сообщение
    не проходит лексический фильтр."""
    norm = normalize_for_matching(text)
    hit: set[str] = set()
    for category, pattern in _COMPILED.items():
        if pattern.search(norm):
            hit.add(category)
    for category, pattern in _COMPILED_DOMAINS.items():
        if pattern.search(norm):
            hit.add(category)
    return hit


def has_marker(text: str) -> bool:
    return bool(find_marker_categories(text))
