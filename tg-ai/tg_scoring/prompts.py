def build_user_message(chunk: Chunk) -> str:
    """Каждое сообщение в своём теге с id: так инструкция из одного
    сообщения не «протекает» на весь чанк. Угловые скобки из текста
    убраны ещё на этапе очистки."""
    lines = [f"chunk_id: {chunk.chunk_id}", "", "<messages>"]
    lines += [f'<msg id="{m.id}">{m.text}</msg>' for m in chunk.messages]
    lines.append("</messages>")
    return "\n".join(lines)


def build_messages(chunk: Chunk, include_fewshot: bool = True) -> list[dict[str, str]]:
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    if include_fewshot:
        messages.append({"role": "user", "content": FEWSHOT_USER})
        messages.append({"role": "assistant", "content": FEWSHOT_ASSISTANT})
    messages.append({"role": "user", "content": build_user_message(chunk)})
    return messages
