def _category_lines() -> str:
    width = max(len(c.key) for c in CATEGORIES)
    return "\n".join(f"{c.key:<{width}} — {c.definition}" for c in CATEGORIES)


def _denied_lines() -> str:
    return ", ".join(DENIED_TOPICS)


